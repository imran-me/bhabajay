// Writes database/seed/quiz.sql from src/data/quizzes.json (text only, no media).
// Usage: node scripts/quiz-sql.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const quizzes = JSON.parse(readFileSync(new URL('../src/data/quizzes.json', import.meta.url), 'utf8'));
const s = (v) => (v === undefined || v === null ? 'NULL' : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);
const dt = (iso) => (iso ? s(new Date(iso).toISOString().slice(0, 19).replace('T', ' ')) : 'NULL');

const out = ['-- Generated by scripts/quiz-sql.mjs — do not edit by hand.', 'SET NAMES utf8mb4;', 'START TRANSACTION;'];
for (const z of quizzes) {
  out.push(
    `INSERT INTO quizzes (slug, kind, title, blurb, opens_at, seconds_per_question) VALUES (${s(z.slug)}, ${s(z.kind)}, ${s(z.title)}, ${s(z.blurb)}, ${dt(z.opensAt)}, ${z.secondsPerQuestion})` +
      ' ON DUPLICATE KEY UPDATE kind=VALUES(kind), title=VALUES(title), blurb=VALUES(blurb), opens_at=VALUES(opens_at), seconds_per_question=VALUES(seconds_per_question);',
  );
  out.push(`DELETE FROM quiz_questions WHERE quiz_slug = ${s(z.slug)};`);
  z.questions.forEach((q, i) => {
    out.push(
      `INSERT INTO quiz_questions (id, quiz_slug, position, question, option_a, option_b, option_c, option_d, answer, fact, image, image_alt, credit) VALUES (${[
        s(q.id), s(z.slug), i, s(q.q), ...q.options.map(s), q.answer, s(q.fact), s(q.image), s(q.imageAlt), s(q.credit),
      ].join(', ')});`,
    );
  });
}
out.push('COMMIT;', '');
mkdirSync(new URL('../database/seed/', import.meta.url), { recursive: true });
writeFileSync(new URL('../database/seed/quiz.sql', import.meta.url), out.join('\n'));
console.log(`quiz.sql: ${quizzes.length} quizzes`);
